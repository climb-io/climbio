export function languageOf(raw = (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage?.()) || 'en') {
  const code = String(raw).replaceAll('-', '_').toLowerCase();
  if (code.startsWith('zh')) return /(?:_cn|_sg|_hans)/.test(code) ? 'zh_CN' : 'zh_TW';
  const base = code.split('_')[0];
  return Object.hasOwn(messages, base) ? base : 'en';
}

export function t(key, ...args) {
  const message = messages[languageOf()]?.[key] ?? messages.en[key];
  if (!message) throw new Error('Unknown collector translation: ' + key);
  return message.replace(/\{(\d+)\}/g, (_, index) => String(args[Number(index)] ?? ''));
}
